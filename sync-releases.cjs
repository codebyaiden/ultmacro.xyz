#!/usr/bin/env node
/**
 * Refresh data/releases.js from the Ultimate Macro GitHub releases.
 *
 *   node sync-releases.cjs
 *
 * Download HTML is generated from this snapshot: every page shares the same
 * version metadata, works without JavaScript, and needs no visitor API call.
 * Other site components may still refresh release metadata at runtime.
 * Re-run it after publishing a release and commit the result.
 *
 * Set GITHUB_TOKEN to raise the anonymous rate limit (optional).
 *
 * It requires src/releases-data.js so the release contract lives in exactly one
 * place, shared with the browser.
 */
const fs = require('node:fs/promises');
const path = require('node:path');
const vm = require('node:vm');
const contract = require('./src/releases-data.js');
const { writeVersionPages, writeVersionChips } = require('./src/version-page.cjs');

const OUT = path.join(__dirname, 'data', 'releases.js');

async function main() {
	const headers = {
		Accept: 'application/vnd.github+json',
		'User-Agent': 'ultmacro.xyz-sync'
	};
	if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;

	const response = await fetch(contract.RELEASES_API, { headers });
	if (!response.ok) {
		console.error(`GitHub responded ${response.status} ${response.statusText}`);
		process.exit(1);
	}

	const incoming = contract.normalizePayload(await response.json());
	if (!incoming.length) {
		console.error('No releases passed the release contract — refusing to write an empty snapshot.');
		process.exit(1);
	}
	let existing = [];
	try {
		const context = { window: {} };
		vm.runInNewContext(await fs.readFile(OUT, 'utf8'), context, { timeout: 1000 });
		existing = context.window.UM_RELEASES.releases;
	} catch (error) {
		if (error.code !== 'ENOENT') throw error;
	}
	const releases = contract.mergeHistory(existing, incoming);

	const snapshot = { repo: contract.REPO, generated: new Date().toISOString(), releases };
	const file =
		'/* Generated by sync-releases.cjs — do not edit by hand. */\n' +
		'window.UM_RELEASES = ' +
		JSON.stringify(snapshot, null, '\t') +
		';\n';

	await fs.writeFile(OUT, file, 'utf8');

	const withAsset = releases.filter((r) => r.asset).length;
	console.log(`Wrote ${releases.length} releases (${withAsset} downloadable) to data/releases.js`);
	for (const r of releases) {
		console.log(
			`  ${r.prerelease ? 'pre ' : '    '}${r.tag.padEnd(12)} ${
				r.asset ? r.asset.name : '— no download'
			}`
		);
	}

	const pages = await writeVersionPages(releases);
	console.log(`\nWrote ${pages.written.length} version pages under download/`);
	for (const tag of pages.written) console.log(`  /download/${tag}`);
	if (pages.latest) console.log(`  /download/latest → ${pages.latest}`);
	for (const tag of pages.removed) console.log(`  removed stale /download/${tag}`);

	if (pages.latest) {
		const chips = await writeVersionChips(pages.latest);
		console.log(`\nStamped ${pages.latest} into ${chips.length} version chips`);
		for (const file of chips) console.log(`  ${file}`);
	}
}

main();
